// Seeded mutations of valid forms: replace, insert or delete one to three characters taken
// from the alphabet of the formats.
const string Alphabet = "0123456789abcdefABCDEFgxX+-{}(), \t";
Random random = new Random(35);
for (int i = 0; i < 1500; i++)
{
    Guid sample = samples[random.Next(samples.Length)];
    List<char> chars = [.. sample.ToString(formats[random.Next(formats.Length)])];
    int edits = random.Next(1, 4);
    for (int e = 0; e < edits; e++)
    {
        int at = random.Next(chars.Count + 1);
        char c = Alphabet[random.Next(Alphabet.Length)];
        switch (random.Next(3))
        {
            case 0 when at < chars.Count:
                chars[at] = c;
                break;
            case 1:
                chars.Insert(at, c);
                break;
            default:
                if (at < chars.Count)
                {
                    chars.RemoveAt(at);
                }
                break;
        }
    }
    inputs.Add(new string([.. chars]));
}

JsonArray cases = [];
HashSet<string> seen = new(StringComparer.Ordinal);
foreach (string input in inputs)
{
    if (!seen.Add(input))
    {
        continue;
    }
    bool ok = Guid.TryParse(input, out Guid value);
    cases.Add(
        new JsonObject
        {
            ["input"] = input,
            ["ok"] = ok,
            ["value"] = ok ? value.ToString("D") : null,
        }
    );
}

JsonObject result = new()
{
    ["generator"] = "rust/tools/guid-oracle",
    ["runtime"] = System.Runtime.InteropServices.RuntimeInformation.FrameworkDescription,
    ["cases"] = cases,
};
File.WriteAllText(
    args[0],
    result.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n"
);
Console.WriteLine($"{cases.Count} cases");
