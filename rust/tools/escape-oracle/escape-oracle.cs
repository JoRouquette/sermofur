// Generates the JSON string-escaping table of the .NET RecordJson (same options as
// src/Sermofur.Application/Contracts.cs). Usage: dotnet run escape-oracle.cs -- OUTPUT.json
#:property PublishAot=false
#:property JsonSerializerIsReflectionEnabledByDefault=true
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.Unicode;

JsonSerializerOptions options = new()
{
    PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    WriteIndented = true,
    Encoder = JavaScriptEncoder.Create(UnicodeRanges.All),
};
options.Converters.Add(new JsonStringEnumConverter(JsonNamingPolicy.SnakeCaseLower, false));

string Escape(string value)
{
    string json = JsonSerializer.Serialize(value, options);
    return json[1..^1];
}

// Escaped scalars are stored as ranges of `\uXXXX` (uppercase hex) plus a short list of
// scalars written another way (short escapes such as `\n`, or a different form).
List<string> specials = [];
List<(int Start, int End)> ranges = [];
int count = 0;
for (int cp = 0; cp <= 0xFFFF; cp++)
{
    if (cp is >= 0xD800 and <= 0xDFFF)
    {
        continue;
    }
    string text = ((char)cp).ToString();
    string escaped = Escape(text);
    if (escaped == text)
    {
        continue;
    }
    count++;
    if (escaped == $"\\u{cp:X4}")
    {
        if (ranges.Count > 0 && ranges[^1].End == cp - 1)
        {
            ranges[^1] = (ranges[^1].Start, cp);
        }
        else
        {
            ranges.Add((cp, cp));
        }
    }
    else
    {
        specials.Add($"[{cp}, {JsonSerializer.Serialize(escaped)}]");
    }
}

// A surrogate in the middle of a run cannot be told from a gap: keep ranges honest by
// splitting at the surrogate block, which no Rust string can hold.
string escapedBmp =
    "\"specials\": [\n      "
    + string.Join(",\n      ", specials)
    + "\n    ],\n"
    + "    \"unicodeEscapedRanges\": [\n      "
    + string.Join(",\n      ", ranges.Select(r => $"[{r.Start}, {r.End}]"))
    + "\n    ]";

StringBuilder supplementary = new();
int sampled = 0;
for (int cp = 0x10000; cp <= 0x10FFFF; cp += 4099)
{
    string text = char.ConvertFromUtf32(cp);
    supplementary.Append(sampled++ == 0 ? "" : ",\n    ");
    supplementary.Append($"[{cp}, {JsonSerializer.Serialize(Escape(text))}]");
}
supplementary.Append(
    $",\n    [{0x10FFFF}, {JsonSerializer.Serialize(Escape(char.ConvertFromUtf32(0x10FFFF)))}]"
);

string document =
    "{\n  \"note\": \"Generated by tools/escape-oracle with the options of RecordJson. Every BMP scalar not listed is written as is.\",\n"
    + "  \"escapedBmp\": {\n    "
    + escapedBmp
    + "\n  },\n"
    + "  \"supplementarySamples\": [\n    "
    + supplementary
    + "\n  ]\n}\n";
File.WriteAllText(args[0], document, new UTF8Encoding(false));
if (args.Length > 1)
{
    // The same ranges as Rust data: the escaping of the .NET encoder follows the Unicode tables
    // of the .NET runtime, so the Rust port pins them instead of deriving them.
    string table =
        "// Generated by rust/tools/escape-oracle from the .NET JavaScriptEncoder (UnicodeRanges.All).\n"
        + "// Do not edit by hand: run the tool again after a change of .NET version.\n"
        + "//\n"
        + "// Inclusive ranges of Basic Multilingual Plane scalars that the .NET encoder writes as\n"
        + "// `\\uXXXX` (uppercase hexadecimal). Scalars outside these ranges, and outside the\n"
        + "// short escapes handled by the caller, are written as they are.\n\n"
        + "pub(crate) const UNICODE_ESCAPED_RANGES: &[(u32, u32)] = &[\n"
        + string.Join("\n", ranges.Select(r => $"    ({r.Start}, {r.End}),"))
        + "\n];\n";
    File.WriteAllText(args[1], table, new UTF8Encoding(false));
}
Console.WriteLine($"escaped BMP scalars: {count}; supplementary samples: {sampled + 1}");
